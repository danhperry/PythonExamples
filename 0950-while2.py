def main():

    names = ['Jodie', 'Lelia', 'Sam', 'George']
    cnt = 0
    while cnt < len(names):
        print(f'{names[cnt]:15s}{names[cnt].upper():15s}')
        cnt += 1








if __name__ == "__main__":
    main()










