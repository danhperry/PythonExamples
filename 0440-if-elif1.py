def main():

    x = 25
    if x == 10:
        print(f'{x} equals 10')
    elif x == 20:
        print(f'{x} equals 20')
    elif x > 30:
        print(f'{x} > 30')
    elif x < 0:
        print(f'{x} < 0')
    else:
        print(f'no match')








if __name__ == "__main__":
    main()
