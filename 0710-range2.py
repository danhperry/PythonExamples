def main():

    x = range(10, 20)
    y = list(x)
    print(y)
    x = range(20, 0, -1)
    y = list(x)
    print(y)
    x = range(10, 30, 2)
    y = list(x)
    print(y)









if __name__ == "__main__":
    main()
