def main():

    x = .1+.2
    y = .3
    print(x)

    if x == y:
        print('x and y are equal')
    if x != y:
        print('x and y are not equal')
    if x > y:
        print('x is greater than y')
    if x >= y:
        print('x is greater than or equal to y')
    if x < y:
        print('x is less than y')
    if x <= y:
        print('x is less than or equal to y')

    print('Done')







if __name__ == "__main__":
    main()
